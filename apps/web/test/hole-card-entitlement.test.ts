describe('a refused frame', () => {
  it('leaves a sentence for the reader, not just a table that stopped moving', () => {
    // Dropping the frame is the safe half. The other half is that a table which silently stops
    // dealing is indistinguishable from a slow one, and the reader — whose opponent's cards this
    // browser has just been handed — is the only person in a position to report what happened.
    const before = { ...EMPTY_TABLE_STATE, view: null };
    const after = tableReducer(before, { kind: 'dataRefused', seats: [2] });
    // Against the module's own sentence, not a copy pasted in here: a test carrying its own copy
    // goes on passing after somebody deletes the wording it was written about.
    assert.equal(after.dataRefusal, dataRefusalSentence([2]));
    assert.match(after.dataRefusal ?? '', /seat 3/u, 'seats are printed 1-based, as everywhere else');
    assert.match(after.dataRefusal ?? '', /Nothing was staked/u);
    // It must not claim the cards were kept from anybody. They arrived; this page declined to draw
    // them. Overclaiming here would be the product lying to the person it leaked to.
    assert.doesNotMatch(after.dataRefusal ?? '', /never (saw|reached)/u);
    // Not the panel headed "The server refused something": this is the opposite direction.
    assert.equal(after.notice, null);
    assert.equal(after.noticeCode, null);
  });

  it('does not clear itself when the next frame looks fine', () => {
    // A server that leaked once sends the same view again a second later. A field that cleared on
    // the next good frame would flicker a warning about the most serious defect this system has.
    const refused = tableReducer(EMPTY_TABLE_STATE, { kind: 'dataRefused', seats: [2] });
    const later = tableReducer(refused, { kind: 'notice', message: 'that seat has gone' });
    assert.equal(later.dataRefusal, refused.dataRefusal);
    assert.equal(tableReducer(later, { kind: 'reset' }).dataRefusal, null);
  });
});
