/** Three seats, 5/10 blinds, a deck this seed deals the same way every run. */
function dealtHand(): HandState {
  return startHand({
    handId: 'hand-entitlement',
    roomId: 'room-entitlement',
    handNumber: 1,
    config: { smallBlind: 5, bigBlind: 10, ante: 0, maxSeats: 6, actionTimeoutSeconds: 30 },
    buttonSeat: 0,
    seats: [
      { seat: 0, playerId: 'p0', stack: 1000 },
      { seat: 1, playerId: 'p1', stack: 1000 },
      { seat: 2, playerId: 'p2', stack: 1000 },
    ],
    random: createDeterministicRandomForTests(7),
  }).state;
}

/**
 * Plays the hand out: the named seats fold at their first opportunity, everybody else takes the
 * most passive legal action until the hand is over.
 *
 * Three endings are wanted and none of them is interchangeable with another. Checking it down
 * reaches a showdown where `result.showdowns` names every seat that opened, and cards may
 * legitimately appear on seats that are not the viewer's. Folding everybody else out reaches
 * `street: 'complete'` with an EMPTY showdown list — the ordinary ending at this product's tables,
 * because the bots fold, and the exact state `scripts/smoke-test.mjs`'s header records a stub API
 * leaking through while the whole smoke run went green. Folding ONE seat out leaves a completed hand
 * containing both kinds of seat at once, which is the case where a check that exempted "a completed
 * hand" rather than "a seat named in the showdown list" would pass.
 */
function playOut(state: HandState, foldSeats: readonly number[] = []): HandState {
  let current = state;
  let guard = 0;
  while (current.toAct !== null && guard < 60) {
    guard += 1;
    const seat = current.toAct;
    const offered = new Set(legalActions(current, seat).map((action) => action.type));
    // Written as a list of literals rather than as `chosen.type`, because `Action` requires a `to`
    // for a raise and the compiler is right to insist: none of these three carries an amount, and
    // this walk must never accidentally size a bet.
    const preference: readonly ('fold' | 'check' | 'call')[] = foldSeats.includes(seat)
      ? ['fold', 'check', 'call']
      : ['check', 'call'];
    const chosen = preference.find((type) => offered.has(type));
    assert.ok(chosen !== undefined, `seat ${String(seat)} was offered no passive action`);
    current = applyAction(current, seat, { type: chosen }).state;
  }
  return current;
}

/** A `state` frame as the wire carries it, with a room summary that satisfies the narrowing. */
function stateFrame(view: PlayerView | null): string {
  return JSON.stringify({
    type: 'state',
    view,
    room: {
      id: 'room-entitlement',
      name: 'Entitlement table',
      ownerUserId: 'p0',
      maxSeats: 6,
      smallBlind: 5,
      bigBlind: 10,
      ante: 0,
      startingStack: 1000,
      actionTimeoutSeconds: 30,
      status: 'open',
      visibility: 'invite_only',
      members: [
        {
          userId: 'p0',
          displayName: 'You',
          seat: 0,
          stack: 1000,
          isBot: false,
          botProfile: null,
          connected: true,
          awaitingBigBlind: false,
        },
      ],
      createdAt: '2026-08-27T00:00:00.000Z',
    },
    deadlineMs: null,
    serverTimeMs: 1_756_000_000_000,
    revision: 1,
  });
}

/**
 * The same view with one seat's real hole cards put back on it — a leak, made the way a broken
 * `redactFor` would make one.
 *
 * The cards come from the `HandState` that dealt them rather than from a literal, so the leaking
 * frame is a frame the server could actually have produced: two real card indices, in the deck this
 * hand committed to, on the seat that is really holding them.
 */
function withLeak(view: PlayerView, state: HandState, seat: number): PlayerView {
  const dealt = state.seats.find((entry) => entry.seat === seat);
  assert.ok(dealt !== undefined && dealt.holeCards !== null, `seat ${String(seat)} was dealt cards`);
  return {
    ...view,
    seats: view.seats.map((entry) =>
      entry.seat === seat ? { ...entry, holeCards: dealt.holeCards } : entry,
    ),
  };
}

