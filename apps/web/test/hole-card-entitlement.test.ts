/**
 * Would this app notice if the API served one player another player's hole cards?
 *
 * ## The residual this file closes
 *
 * `docs/VERIFICATION.md` §12 said, after the hidden-information sweep of 2026-08-27:
 *
 *     **The web app would render a leak.** Hole-card redaction has ONE boundary — `redactFor` on
 *     the server. `apps/web`'s `isSeatView` accepts `holeCards` on any seat and `Seat.tsx` draws
 *     them face-up, so a leaking API would be rendered faithfully. The three "a card the server hid
 *     stays hidden" tests in `a11y-contracts.test.ts` are regexes over SOURCE TEXT and only ask what
 *     happens when `holeCards === null`; **no test in `apps/web` would fail if the API leaked.**
 *
 * Every word of that was true. The three tests it names assert that `Seat.tsx` still contains the
 * line `const faceDown = holeCards === null;` and that the face-down branch of `PlayingCard` does
 * not touch the decoded card — both worth keeping, and both about the case where the server sent
 * nothing. A leak is the other case, and they cannot see it: the source they read is correct, and
 * correct source rendering a dishonest frame renders a dishonest frame.
 *
 * ## Why the data here is not written by hand
 *
 * Both halves run the real producers.
 *
 * The live half calls `startHand`, drives a whole hand through `applyAction`, and takes its frames
 * from `redactFor` — the actual redaction boundary, in `@prl/poker-engine`, the same function the
 * API calls through `LiveTable.viewFor`. The clean frames are therefore not this file's opinion of
 * what a clean frame looks like; the leaking ones are made by moving a card the same `HandState`
 * genuinely dealt onto a seat that was not entitled to it, which is exactly the shape a broken
 * `redactFor` would emit. A hand-written fixture would have proved that the check agrees with the
 * fixture's author.
 *
 * The review half uses `REVIEW_HAND_SHOWDOWN` and `REVIEW_HAND_FOLDED` from `src/fixtures/review.ts`,
 * which `/review/[handId]`'s own header records as having been generated by running the real
 * `buildHandReview` over hand-shaped rows, and passes them through `buildHandReplay` — the module
 * the page actually renders from.
 *
 * ## A sweep of nothing is not a pass
 *
 * `checkHoleCardEntitlement` returns `seatsWithCards` for this reason: `unentitled.length === 0` is
 * also what a view with no seats produces, what a payload whose `holeCards` were all dropped by a
 * serialiser produces, and what a renamed field produces. Every clean case below asserts the sweep
 * had cards to look at, and the count comes from the function rather than from this file counting
 * its own fixture.
 *
 * ## The negative control
 *
 * Run on 2026-08-27 by deleting the single `checkHoleCardEntitlement` line from `narrowState` in
 * `src/lib/table-socket.ts` and running the two files that exercise it:
 *
 *     test/hole-card-entitlement.test.ts   15 tests, 11 pass, 4 fail
 *     test/table-socket.test.ts            17 tests, 16 pass,  1 fail
 *
 * The five failures are exactly the five cases that feed a leaking frame to `readServerMessage` or
 * to a live socket, each reporting `ok: true` — the frame accepted, and on its way to a renderer
 * that would have drawn the cards. Everything asserting that an honest frame is accepted stayed
 * green, and so did the whole review half, which does not go through that line. The line was
 * restored and both files passed in full. Without the guard the leak is rendered; with it the frame
 * is refused; and the guard is not passing by refusing everything.
 */

