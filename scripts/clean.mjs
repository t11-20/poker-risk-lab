#!/usr/bin/env node
/**
 * Deletes build output across the workspace: `dist/`, `.next/`, `coverage/` and
 * `*.tsbuildinfo`.
 *
 * This is what `pnpm run clean` does.
 *
 * ## Why a script this small is this careful
 *
 * The one-liner people reach for is
 * `find . -name dist -type d -prune -exec rm -rf {} +`, and it is a foot-gun for
 * three separate reasons:
 *
 *   1. It matches inside `node_modules`. Plenty of installed packages ship a
 *      `dist/` directory, and deleting those leaves a dependency tree that still
 *      satisfies `verifyDepsBeforeRun` (the manifests are intact) while failing
 *      at import time. The symptom is "my imports broke and I have no idea why",
 *      and the fix is a full reinstall — but only after you work out what
 *      happened.
 *
 *   2. It follows symlinks. `nodeLinker: isolated` makes this repo's node_modules
 *      a dense farm of relative symlinks, and a workspace can perfectly well
 *      contain a link that resolves outside the repository.
 *
 *   3. It has no idea where the repository is. Run from the wrong directory it
 *      does the same thing somewhere else.
 *
 * So: the walk never descends into `node_modules` (or `.git`, or the pnpm store);
 * every candidate is canonicalised and checked to be inside the repository root
 * before anything is unlinked; a candidate that turns out to be a symlink is
 * reported and skipped rather than followed; and every deletion is printed with
 * its size, because a clean script that says nothing is a clean script you cannot
 * audit after the fact.
 *
 * `--dry-run` prints exactly what would go, and deletes nothing. If you are about
 * to run this in an unfamiliar checkout, run that first.
 *
 * ## What is NOT deleted
 *
 * `node_modules` — that is `rm -rf node_modules && pnpm install`, a different and
 * much slower operation, and conflating the two means every "clean" costs a
 * reinstall. `.env` and anything else untracked. `docs/sbom/*.json`, which are
 * audit evidence regenerated by the supply-chain gates rather than build output.
 */

import { readdirSync, rmSync, statSync } from 'node:fs';
import { lstat, realpath } from 'node:fs/promises';
import { basename, dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const NO_COLOR = process.env.NO_COLOR !== undefined || !process.stdout.isTTY;
const paint = (code, s) => (NO_COLOR ? s : `\u001b[${code}m${s}\u001b[0m`);
const dim = (s) => paint('2', s);
const bold = (s) => paint('1', s);
const red = (s) => paint('31', s);
const yellow = (s) => paint('33', s);
const green = (s) => paint('32', s);

const dryRun = process.argv.includes('--dry-run') || process.argv.includes('-n');

if (process.argv.includes('--help') || process.argv.includes('-h')) {
  console.log(`
${bold('pnpm run clean')} — remove build output from this workspace

  Deletes, anywhere under the repository root except node_modules:
    dist/          compiled TypeScript output
    .next/         Next.js build output
    coverage/      coverage reports
    *.tsbuildinfo  incremental compilation state

  Options:
    -n, --dry-run   list what would be deleted, delete nothing
    -h, --help      this text

  Does not touch node_modules. To reset dependencies instead:
    rm -rf node_modules && pnpm install --frozen-lockfile
`);
  process.exit(0);
}

/** Directory names the walk refuses to enter. */
const DO_NOT_DESCEND = new Set(['node_modules', '.git', '.pnpm-store']);

/**
 * Directory names to delete on sight, and the file suffix to delete.
 *
 * Kept as data rather than spread through the code so that adding a target is a
 * one-line change with an obvious blast radius. If you add one, make sure it
 * cannot appear inside a dependency for a legitimate reason.
 */
const DELETE_DIRS = new Set(['dist', '.next', 'coverage']);
const DELETE_SUFFIX = '.tsbuildinfo';

/**
 * True only when `candidate` is the root itself or genuinely beneath it.
 *
 * The `+ sep` matters: a plain `startsWith(root)` also accepts a sibling
 * directory whose name merely begins with the root's name — for
 * /home/x/poker-risk-lab it would happily accept /home/x/poker-risk-lab-backup.
 */
function isInsideRepo(candidate) {
  if (candidate === REPO_ROOT) return true;
  return candidate.startsWith(REPO_ROOT + sep);
}

function formatBytes(bytes) {
  if (bytes < 1024) return `${bytes} B`;
  const units = ['KiB', 'MiB', 'GiB'];
  let value = bytes / 1024;
  let unit = 0;
  while (value >= 1024 && unit < units.length - 1) {
    value /= 1024;
    unit += 1;
  }
  return `${value.toFixed(value < 10 ? 1 : 0)} ${units[unit]}`;
}

/** Recursive size, for the report. Never follows symlinks; counts them as 0. */
function sizeOf(path) {
  let total = 0;
  const stack = [path];
  while (stack.length > 0) {
    const current = stack.pop();
    if (current === undefined) break;
    let entries;
    try {
      entries = readdirSync(current, { withFileTypes: true });
    } catch {
      // Unreadable or not a directory: fall back to a single stat.
      try {
        total += statSync(current).size;
      } catch {
        // Vanished between listing and stat. Nothing to count.
      }
      continue;
    }
    for (const entry of entries) {
      const full = join(current, entry.name);
      if (entry.isSymbolicLink()) continue;
      if (entry.isDirectory()) {
        stack.push(full);
        continue;
      }
      try {
        total += statSync(full).size;
      } catch {
        // Same race as above.
      }
    }
  }
  return total;
}

/**
 * Collects deletion candidates.
 *
 * A matched directory is not descended into: everything inside it is going
 * anyway, and walking a large `.next/` to find nested `dist/` directories is
 * wasted work.
 */
function collect(dir, found) {
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch (err) {
    console.log(yellow(`  ! cannot read ${relative(REPO_ROOT, dir)}: ${err.message}`));
    return;
  }
  for (const entry of entries) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (DO_NOT_DESCEND.has(entry.name)) continue;
      if (DELETE_DIRS.has(entry.name)) {
        found.push({ path: full, kind: 'dir' });
        continue;
      }
      collect(full, found);
      continue;
    }
    // A symlink named `dist` is recorded so it can be refused loudly below,
    // rather than silently ignored — an unexpected symlink where a build
    // directory should be is worth a human look.
    if (entry.isSymbolicLink()) {
      if (DELETE_DIRS.has(entry.name) || entry.name.endsWith(DELETE_SUFFIX)) {
        found.push({ path: full, kind: 'symlink' });
      }
      continue;
    }
    if (entry.isFile() && entry.name.endsWith(DELETE_SUFFIX)) {
      found.push({ path: full, kind: 'file' });
    }
  }
}

/**
 * Final gate before anything is unlinked.
 *
 * The candidate's *parent* is canonicalised rather than the candidate itself: the
 * candidate is about to be deleted and may be a symlink, and resolving a symlink
 * to decide whether it is safe to delete answers the wrong question. What matters
 * is that the directory entry we are removing lives inside this repository.
 */
async function verifySafe(candidatePath, realRoot) {
  const parentReal = await realpath(dirname(candidatePath));
  const resolvedCandidate = join(parentReal, basename(candidatePath));

  if (!(parentReal === realRoot || parentReal.startsWith(realRoot + sep))) {
    return { ok: false, reason: `parent resolves outside the repository (${parentReal})` };
  }
  if (!isInsideRepo(resolvedCandidate)) {
    return { ok: false, reason: 'resolves outside the repository' };
  }
  // Belt and braces: even if the walk were changed later, nothing under a
  // node_modules directory is ever deleted by this script.
  const segments = relative(realRoot, resolvedCandidate).split(sep);
  if (segments.includes('node_modules')) {
    return { ok: false, reason: 'inside node_modules' };
  }
  const stats = await lstat(resolvedCandidate);
  if (stats.isSymbolicLink()) {
    return { ok: false, reason: 'is a symlink — refusing to delete it, look at it by hand' };
  }
  return { ok: true, resolved: resolvedCandidate };
}

// --- run ------------------------------------------------------------------

const realRoot = await realpath(REPO_ROOT);

console.log(bold(`\nclean${dryRun ? ' (dry run)' : ''}`));
console.log(dim(`  root ${realRoot}\n`));

const candidates = [];
collect(realRoot, candidates);
candidates.sort((a, b) => a.path.localeCompare(b.path));

let deleted = 0;
let freed = 0;
let refused = 0;

for (const candidate of candidates) {
  const rel = relative(realRoot, candidate.path) || '.';
  let verdict;
  try {
    verdict = await verifySafe(candidate.path, realRoot);
  } catch (err) {
    console.log(yellow(`  ! skipped ${rel} — ${err.message}`));
    refused += 1;
    continue;
  }
  if (!verdict.ok) {
    console.log(red(`  ! refused ${rel} — ${verdict.reason}`));
    refused += 1;
    continue;
  }

  const bytes = sizeOf(verdict.resolved);
  if (dryRun) {
    console.log(`  ${dim('would delete')} ${rel} ${dim(`(${formatBytes(bytes)})`)}`);
    deleted += 1;
    freed += bytes;
    continue;
  }
  try {
    rmSync(verdict.resolved, { recursive: true, force: true });
  } catch (err) {
    console.log(red(`  ! failed to delete ${rel} — ${err.message}`));
    refused += 1;
    continue;
  }
  console.log(`  ${green('deleted')} ${rel} ${dim(`(${formatBytes(bytes)})`)}`);
  deleted += 1;
  freed += bytes;
}

if (candidates.length === 0) {
  console.log(dim('  nothing to clean'));
}

console.log(
  `\n${bold('Summary')}  ${deleted} ${dryRun ? 'would be removed' : 'removed'}, ${formatBytes(freed)} ${
    dryRun ? 'would be freed' : 'freed'
  }${refused > 0 ? `, ${refused} refused` : ''}\n`,
);

// A refusal is a finding, not a nuisance: it means something in the tree is not
// shaped the way this script expects. Exit non-zero so a script that chains off
// `pnpm run clean` stops and someone reads the message.
process.exitCode = refused > 0 ? 1 : 0;
